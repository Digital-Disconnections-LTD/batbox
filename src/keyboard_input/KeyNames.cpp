bool isShiftKey(const std::string& code){
  static const std::vector<std::string> codes={"[a","[b","[c","[d","[e","[2$","[3$","[5$","[6$","[7$","[8$","[Z"};
  return std::find(codes.begin(),codes.end(),code)!=codes.end();
}
bool isCtrlKey(const std::string& code){
  static const std::vector<std::string> codes={"Oa","Ob","Oc","Od","Oe","[2^","[3^","[5^","[6^","[7^","[8^"};
  return std::find(codes.begin(),codes.end(),code)!=codes.end();
}
