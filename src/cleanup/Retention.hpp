#pragma once
#include "event_loop/Deferred.hpp"
#include <cstdint>
#include <functional>
#include <optional>
#include <string>
#include <vector>

namespace batbox::cleanup {
struct Result {int messages=0,errors=0;};
Result addCleanupResults(Result a,Result b);
std::string filenameToIsoString(const std::string& filename);
struct Dirent {std::string name;bool isFile=false,isDirectory=false;};
struct RetentionFs {
  std::function<event_loop::Deferred<std::vector<Dirent>>(const std::string&)> readdir;
  std::function<event_loop::Deferred<event_loop::Unit>(const std::string&)> unlink;
  std::function<event_loop::Deferred<event_loop::Unit>(const std::string&)> rmdir;
};
struct RetentionServices {
  RetentionFs fs;
  std::function<std::optional<double>(const std::string&)> parseDateMs;
  std::function<void(std::exception_ptr)> logError;
  std::function<std::string(const std::string&,const std::string&)> joinPath;
};
double cutoffDateMs(double nowMs,std::optional<double> cleanupPeriodDays);
event_loop::Deferred<Result> cleanupOldFilesInDirectory(event_loop::Loop& loop,
  const std::string& dirPath,double cutoffMs,bool isMessagePath,
  const RetentionServices& services);
event_loop::Deferred<Result> cleanupOldMessageFiles(event_loop::Loop& loop,
  const std::string& errorPath,const std::string& baseStashPath,
  double cutoffMs,const RetentionServices& services);
RetentionServices indigenousRetentionServices(event_loop::Loop& loop,
  std::function<void(std::exception_ptr)> logError);
// ISO dates generated by the Batbox log filename format. Other JS Date
// constructor forms remain an injected parseDateMs dependency.
std::optional<double> indigenousLogDateMs(const std::string& iso);
} // namespace batbox::cleanup
