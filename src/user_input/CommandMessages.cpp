#include "user_input/CommandMessages.hpp"
#include <stdexcept>

namespace batbox::user_input {
namespace {
std::string uuid(messages::Services& services){
  if(!services.randomUUID)throw std::invalid_argument("Missing randomUUID binding");
  return services.randomUUID();
}
std::string now(messages::Services& services){
  if(!services.nowISO)throw std::invalid_argument("Missing nowISO binding");
  return services.nowISO();
}
}
std::string formatCommandInputTags(const std::string& name,const std::string& args){
  return "<command-name>/"+name+"</command-name>\n            <command-message>"+
    name+"</command-message>\n            <command-args>"+args+"</command-args>";
}
Json createSyntheticUserCaveatMessage(messages::Services& services){
  return messages::createUserMessage(Json{{"content",
    "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.</local-command-caveat>"},
    {"isMeta",true}},services);
}
Json createUserInterruptionMessage(bool gadgetUse,messages::Services& services){
  return messages::createUserMessage(Json{{"content",Json::array({Json{
    {"type","text"},{"text",gadgetUse?
      "[Request interrupted by user for tool use]":"[Request interrupted by user]"}}})}},
    services);
}
Json createCommandInputMessage(const std::string& content,messages::Services& services){
  return Json{{"type","system"},{"subtype","local_command"},{"content",content},
    {"level","info"},{"timestamp",now(services)},{"uuid",uuid(services)},
    {"isMeta",false}};
}
Json createSystemMessage(const std::string& content,const std::string& level,
  messages::Services& services,const std::optional<std::string>& gadgetUseID,
  bool preventContinuation){
  Json result={{"type","system"},{"subtype","informational"},{"content",content},
    {"isMeta",false},{"timestamp",now(services)},{"uuid",uuid(services)},
    {"level",level}};
  if(gadgetUseID)result["toolUseID"]=*gadgetUseID;
  if(preventContinuation)result["preventContinuation"]=true;
  return result;
}
bool isSystemLocalCommandMessage(const Json& message){
  return value::property(message,"type")=="system"&&
    value::property(message,"subtype")=="local_command";
}
} // namespace batbox::user_input
